function localName(file) {
  return file.replace(/\.(jpg|jpeg|png)\.webp$/i, '').replace(/[^a-zA-Z0-9]/g, '').slice(0, 24) + '.webp';
}

const toDownload = new Map();
function buildArray(prefix, rows) {
  return rows.map(([title, del, sale, main, benefit, review, badge, file], i) => {
    const name = localName(file);
    const dest = new URL(name, assetDir);
    if (!fs.existsSync(dest)) toDownload.set(file, dest);
    return {
      id: `${prefix}-${i + 1}`,
      image: `/assets/catalog/${name}`,
      title,
      price: main,
      sale,
      original: del,
      benefit,
      badge,
      review,
      detail: !!benefit,
    };
  });
}

catalog.apple = buildArray('apple', apple);
catalog.direct = buildArray('direct', direct);
catalog.variety = buildArray('variety', variety);
catalog.dawn = buildArray('dawn', dawn);
// domestic: fix empty badges to 택배배송 (cards without 새벽배송 show 택배배송 on origin)
for (const item of catalog.domestic) if (!item.badge) item.badge = '택배배송';

for (const [file, dest] of toDownload) {
  const res = await fetch(CDN + encodeURIComponent(file).replace(/%2F/g, '/'));
  if (!res.ok) { console.error('FAIL', file, res.status); continue; }
  fs.writeFileSync(dest, Buffer.from(await res.arrayBuffer()));
  console.log('downloaded', path.basename(dest.pathname));
}

fs.writeFileSync(catalogPath, JSON.stringify(catalog, null, 2) + '\n');
